/** Register or override a UI schema (used by local workflows/tools). */
export function registerUiSchema(s: UiSchema): void {
  if (!validateUiSchema(s)) throw new Error('invalid UiSchema');
  CATALOG.set(s.kind, s);
}

export function uiSchemaFor(kind: string): UiSchema | undefined {
  return CATALOG.get(kind);
}

export function uiCatalog(): UiSchema[] {
  return [...CATALOG.values()];
}
