/**
 * ZeroAI adaptive UI contract — schema-driven rendering.
 *
 * The edge decides *what* to show (a UiSchema); the client renders it
 * generically. Schemas are plain JSON so they can cross the bridge,
 * be persisted, or be generated by local workflows without code changes.
 */

export type UiComponentKind =
  | 'heading'
  | 'text'
  | 'status'
  | 'badge'
  | 'field'
  | 'form'
  | 'table'
  | 'action'
  | 'confirm'
  | 'json';

export interface UiComponent {
  id: string;
  kind: UiComponentKind;
  /** Optional binding to a response/decision field, e.g. 'locality'. */
  bind?: string;
  props?: Record<string, unknown>;
  children?: UiComponent[];
}

export interface UiSchema {
  version: 'ultra.ui.v1';
  /** Catalog key this schema was selected for (chat, confirm, results...). */
  kind: string;
  title?: string;
  description?: string;
  components: UiComponent[];
}

const KINDS: UiComponentKind[] = [
  'heading',
  'text',
  'status',
  'badge',
  'field',
  'form',
  'table',
  'action',
  'confirm',
  'json',
];

export function validateUiSchema(s: unknown): s is UiSchema {
  if (typeof s !== 'object' || s === null) return false;
  const v = s as UiSchema;
  if (v.version !== 'ultra.ui.v1') return false;
  if (typeof v.kind !== 'string' || !Array.isArray(v.components)) return false;
  const walk = (c: UiComponent): boolean => {
    if (typeof c.id !== 'string' || !KINDS.includes(c.kind)) return false;
    return (c.children ?? []).every(walk);
  };
  return v.components.every(walk);
}

function schema(
  kind: string,
  title: string,
  components: UiComponent[]
): UiSchema {
  return { version: 'ultra.ui.v1', kind, title, components };
}

/**
 * Built-in schema catalog. Local workflows may register additional
 * schemas via registerUiSchema; the renderer treats all uniformly.
 */
const CATALOG = new Map<string, UiSchema>();

function def(s: UiSchema): void {
  CATALOG.set(s.kind, s);
}

